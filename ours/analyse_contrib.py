def load(ds, name, seeds):
    start = int(VAL_FRAC * N_TEST[ds])
    tr, ytr, te, yte, dr = rx.load(ds)
    drs = [d - start for d in dr if d > start + 300]
    rows, ev, extra = [], [], []
    for s in seeds:
        f = f"{OUT}/eval/{ds}__{name}__s{s}.npz"
        if not os.path.exists(f):
            return None
        z = np.load(f, allow_pickle=True)
        m = full_metrics(z["y"][start:], z["pred"][start:], z["p1"][start:], z["lat"][start:], drs, int(z["y"][start - 1]))
        rows.append(m); ev.append(json.loads(str(z["events"]))); extra.append((int(z["replaced"]), float(z["active"][start:].mean()) if z["active"].size > 1 else 0.0, z["pred"][start:], z["y"][start:]))
    return rows, ev, extra


def cell(vals, k):
    v = np.array([r[k] for r in vals], float) * SCALE.get(k, 1)
    if np.isnan(v).all():
        return v, "n/a"
    sd = v.std(ddof=1) if len(v) > 1 else 0
    return v, f"{v.mean():.2f}±{sd:.2f}" if abs(v.mean()) >= 1 else f"{v.mean():.3f}±{sd:.3f}"


def paired(a, b, k):
    d = np.array([x[k] - y[k] for x, y in zip(a, b)], float) * SCALE.get(k, 1)
    if len(d) < 2 or np.allclose(d, d[0]):
        return d.mean(), 0.0, False
    h = stats.t.ppf(0.975, len(d) - 1) * d.std(ddof=1) / np.sqrt(len(d))
    return d.mean(), h, abs(d.mean()) > h


def table(ds, names, cols, ref="B0"):
    R = {n: load(ds, n, EVAL_SEEDS[ds]) for n in names}
    R = {n: r for n, r in R.items() if r}
    out = "| variant | " + " | ".join(cols) + " | alarms | replaced | ensemble-on |\n|---|" + "---|" * (len(cols) + 3) + "\n"
    for n, (rows, ev, ex) in R.items():
        cells = [cell(rows, k)[1] for k in cols]
        al = np.mean([len(e) for e in ev]); rp = np.mean([x[0] for x in ex]); on = np.mean([x[1] for x in ex])
        out += f"| {NICE.get(n, n)} | " + " | ".join(cells) + f" | {al:.1f} | {rp:.1f} | {on * 100:.0f}% |\n" if n in ("G",) else \
               f"| {NICE.get(n, n)} | " + " | ".join(cells) + f" | {al:.1f} | {rp:.1f} | - |\n"
    return out, R


def impact(ds, R, names, cols, ref):
    out = f"| vs **{NICE[ref]}** | " + " | ".join(cols) + " |\n|---|" + "---|" * len(cols) + "\n"
    for n in names:
        if n not in R or ref not in R:
            continue
        cells = []
        for k in cols:
            m, h, sig = paired(R[n][0], R[ref][0], k)
            if np.isnan(m):
                cells.append("n/a"); continue
            cells.append(f"{m:+.2f} ±{h:.2f}{' *' if sig else ''}")
        out += f"| {NICE[n]} | " + " | ".join(cells) + " |\n"
    return out


